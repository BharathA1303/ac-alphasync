@router.post("/courses/{course_id}/assessments/{assessment_id}/regenerate-questions")
async def regenerate_assessment_questions(
    course_id: str,
    assessment_id: str,
    faculty: User = Depends(require_faculty),
    db: AsyncSession = Depends(get_db),
):
    course = await _get_own_course(db, faculty, course_id)
    _assert_editable(course)
    assessment = await _get_own_assessment(db, course, assessment_id)

    target_uuids = []
    if assessment.lesson_ids and isinstance(assessment.lesson_ids, list):
        target_uuids = [_as_uuid(lid) for lid in assessment.lesson_ids if _as_uuid(lid)]

    if target_uuids:
        lessons_res = await db.execute(select(Lesson).where(Lesson.course_id == course.id, Lesson.id.in_(target_uuids)))
    else:
        lessons_res = await db.execute(select(Lesson).where(Lesson.course_id == course.id))

    lessons = lessons_res.scalars().all()
    lesson_ids = [l.id for l in lessons]

    texts = [f"{l.title}\n{l.content or ''}\n{l.extracted_text or ''}".strip() for l in lessons]
    if lesson_ids:
        try:
            mats_res = await db.execute(select(LessonMaterial.extracted_text).where(LessonMaterial.lesson_id.in_(lesson_ids)))
            texts.extend([t[0] for t in mats_res.all() if t[0]])
        except Exception:
            pass

    material_text = "\n\n".join([t for t in texts if t]).strip()
    if not material_text:
        material_text = f"Course Title: {course.title}\nDescription: {course.description or 'Stock market trading fundamentals, technical analysis, and risk management.'}"

    try:
        mcqs = await generate_mcq_questions(
            material_text=material_text,
            question_count=assessment.question_count,
            difficulty=assessment.difficulty,
            course_title=course.title,
        )
    except AssessmentAIError as e:
        raise HTTPException(status_code=400, detail=str(e))

    existing_qs = await db.execute(select(Question).where(Question.assessment_id == assessment.id))
    for q in existing_qs.scalars().all():
        await db.delete(q)
    await db.commit()

    created_questions = []
    for idx, item in enumerate(mcqs):
        q = Question(
            assessment_id=assessment.id,
            order_index=idx,
            source="ai",
            text=item["text"].strip(),
        )
        db.add(q)
        await db.commit()
        await db.refresh(q)

        created_choices = []
        for c_idx, choice_data in enumerate(item["choices"]):
            c = Choice(
                question_id=q.id,
                text=choice_data["text"].strip(),
                is_correct=bool(choice_data.get("is_correct", False)),
                order_index=c_idx,
            )
            db.add(c)
            created_choices.append(c)

        await db.commit()
        created_questions.append(_question_out(q, created_choices))

    return {"success": True, "questions": created_questions}


