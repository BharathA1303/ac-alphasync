def _course_out(course: Course, lesson_count: int = 0, assessment_count: int = 0) -> dict:
    return {
        "id": str(course.id),
        "title": course.title,
        "description": course.description,
        "status": course.status,
        "review_note": course.review_note,
        "reviewed_at": _iso(course.reviewed_at),
        "lesson_count": lesson_count,
        "assessment_count": assessment_count,
        "created_at": _iso(course.created_at),
        "updated_at": _iso(course.updated_at),
    }


def _lesson_out(lesson: Lesson, materials: list = None) -> dict:
    return {
        "id": str(lesson.id),
        "title": lesson.title,
        "content": lesson.content,
        "order_index": lesson.order_index,
        "file_url": lesson.file_url,
        "file_name": lesson.file_name,
        "file_type": lesson.file_type,
        "has_extracted_text": bool(lesson.extracted_text),
        "materials": materials or (
            [
                {
                    "id": f"primary-{lesson.id}",
                    "file_url": lesson.file_url,
                    "file_name": lesson.file_name,
                    "file_type": lesson.file_type,
                    "has_extracted_text": bool(lesson.extracted_text),
                }
            ] if lesson.file_url else []
        ),
    }


def _question_out(question: Question, choices: list[Choice]) -> dict:
    return {
        "id": str(question.id),
        "text": question.text,
        "source": question.source,
        "order_index": question.order_index,
        "choices": [
            {"id": str(c.id), "text": c.text, "is_correct": c.is_correct, "order_index": c.order_index}
            for c in sorted(choices, key=lambda c: c.order_index)
        ],
    }


def _assessment_out(assessment: Assessment, question_count: int = 0) -> dict:
    return {
        "id": str(assessment.id),
        "title": assessment.title,
        "instructions": assessment.instructions,
        "pass_score": assessment.pass_score,
        "question_count": assessment.question_count,
        "difficulty": assessment.difficulty,
        "lesson_ids": assessment.lesson_ids or [],
        "generated_question_count": question_count,
    }


