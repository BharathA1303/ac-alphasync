"""
Faculty Course Builder API — scoped strictly to the caller's own institution
and their own authored courses.

A faculty member uploads a course (status="pending"); it is only visible to
students once their Institution Admin approves it (see routes/institution_admin.py).
Faculty can always see and edit their own courses regardless of status, but
never another faculty member's courses. Once approved, a course's content
locks — edits require the Institution Admin.

Lessons may carry one uploaded material file (PDF/DOCX/PPTX/MD); its text is
extracted and stored so it can be used as AI context for MCQ generation.
Assessments hold structured multiple-choice Questions/Choices, added either
manually or generated by AI from the course's lesson material.
"""

