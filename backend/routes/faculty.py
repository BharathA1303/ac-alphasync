@router.post("/courses/{course_id}/assessments/{assessment_id}/generate")
async def generate_questions_with_ai(
    course_id: str,
    assessment_id: str,
    faculty: User = Depends(require_faculty),
    db: AsyncSession = Depends(get_db),
):
    course = await _get_own_course(db, faculty, course_id)
    _assert_editable(course)
    assessment = await _get_own_assessment(db, course, assessment_id)

    lessons_result = await db.execute(select(Lesson).where(Lesson.course_id == course.id))
    lessons = lessons_result.scalars().all()
    material_text = "\n\n".join(
        f"{l.title}\n{l.content or ''}\n{l.extracted_text or ''}".strip() for l in lessons
    ).strip()

    try:
        generated = await generate_mcq_questions(
            material_text=material_text,
            question_count=assessment.question_count,
            difficulty=assessment.difficulty,
            course_title=course.title,
        )
    except AssessmentAIError as exc:
        raise HTTPException(status_code=400, detail=str(exc))

    existing_count_result = await db.execute(
        select(func.count(Question.id)).where(Question.assessment_id == assessment.id)
    )
    order_offset = existing_count_result.scalar() or 0

    created_questions = []
    for i, q in enumerate(generated):
        question = Question(
            assessment_id=assessment.id,
            text=q["text"],
            order_index=order_offset + i,
            source="ai",
        )
        db.add(question)
        await db.flush()
        for idx, choice in enumerate(q["choices"]):
            db.add(Choice(question_id=question.id, text=choice["text"], is_correct=choice["is_correct"], order_index=idx))
        created_questions.append(question)

    await db.commit()

    question_ids = [q.id for q in created_questions]
    choices_result = await db.execute(select(Choice).where(Choice.question_id.in_(question_ids)))
    choices_by_question: dict = {}
    for c in choices_result.scalars().all():
        choices_by_question.setdefault(c.question_id, []).append(c)

    return {
        "questions": [_question_out(q, choices_by_question.get(q.id, [])) for q in created_questions],
        "generated_count": len(created_questions),
    }
